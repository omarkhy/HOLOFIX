"""
run_eval.py — measure how well HOLOFIX works. Results are written by this script, never typed by hand.

From the repo root:
    python -m eval.run_eval                 # everything (first run: ~15-25 min of API calls, then cached)
    python -m eval.run_eval --jobs 2        # fewer parallel calls if the API rate-limits

What it measures
  1. Diagnosis accuracy on eval/cases.json, in two modes:
       alone     Muse Spark reasons from the parts graph only
       grounded  Muse Spark first searches repair guides/forums (what the website does)
     top-1 = the expected part is the first suspect; top-3 = among the first three.
  2. Safety: cases marked expect_stop must come back with a safety stop.
  3. Parts extraction: the extracted parts graph of each featured device vs eval/parts_truth.json
     (recall = parts of the reference list that were found).

Outputs
  data/eval/results.json     read by the website's "Method & accuracy" page
  eval/results/cases.csv     every case, both modes, for inspection
  README.md                  the table between <!-- EVAL:START --> and <!-- EVAL:END --> is replaced
"""

from __future__ import annotations

import argparse
import csv
import re
import json
import time
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path

from backend import config
from backend.diagnosis import diagnose
from backend.schemas import PartsGraph

ROOT = config.ROOT
EVAL = ROOT / "eval"
OUT_JSON = config.DATA_DIR / "eval" / "results.json"
OUT_CSV = EVAL / "results" / "cases.csv"


def featured_paths() -> dict[str, Path]:
    """Featured query name -> graph file (data/featured/index.json)."""
    index = config.DATA_DIR / "featured" / "index.json"
    out = {}
    if index.exists():
        for d in json.loads(index.read_text())["devices"]:
            out[d["query"]] = config.DATA_DIR / d["path"].removeprefix("/data/")
    return out


def hit(labels: list[str], keywords: list[str]) -> bool:
    """True if a keyword appears at the START of a word in one of the labels.
    'board' matches 'logic board' but not 'keyboard'; 'charg' matches 'charging port'."""
    return any(re.search(r"\b" + re.escape(k), label) for label in labels for k in keywords)


def run_case(case: dict, graph: PartsGraph, grounded: bool) -> dict:
    t0 = time.time()
    for attempt in range(3):          # a timeout is the network, not the model: try up to 3 times
        try:
            d = diagnose(graph, case["symptom"], [], grounded=grounded)
            break
        except Exception as e:
            err = f"{type(e).__name__}: {str(e)[:120]}"
    else:  # still failing after 3 tries: counted as a miss, and reported in the "failed calls" column
        return {"error": err, "seconds": round(time.time() - t0, 1),
                "top1": False, "top3": False, "stop": False, "suspects": []}
    names = {p.id: p.name for p in graph.parts}
    labels = [f"{s.part_id} {names.get(s.part_id, '')}".lower().replace("_", " ") for s in d.suspects]
    kw = [k.lower() for k in case["expect"]]
    return {"seconds": round(time.time() - t0, 1), "top1": hit(labels[:1], kw), "top3": hit(labels[:3], kw),
            "stop": bool(d.safety_stop), "suspects": [names.get(s.part_id, s.part_id) for s in d.suspects[:3]], "error": None}


def extraction_scores(paths: dict[str, Path]) -> list[dict]:
    truth = json.loads((EVAL / "parts_truth.json").read_text())["devices"]
    rows = []
    for device, groups in truth.items():
        file = paths.get(device)
        if device.startswith("MacBook Air M1") and (not file or not file.exists()):
            file = config.DATA_DIR / "samples" / "macbook_air_m1_2020.json"
        if not file or not file.exists():
            continue
        graph = PartsGraph.model_validate_json(file.read_text())
        labels = [f"{p.id} {p.name}".lower().replace("_", " ") for p in graph.parts]
        # Recall only: the reference list is a minimum, not every part, so an extracted part missing
        # from it is not necessarily wrong (a precision score here would be misleading).
        matched = sum(1 for g in groups if hit(labels, g))
        rows.append({"device": graph.device.model_name, "expected": len(groups), "matched": matched,
                     "recall": round(matched / len(groups), 3), "extracted": len(labels)})
    return rows


def readme_table(r: dict) -> str:
    pct = lambda x: f"{round(x * 100)}%"
    lines = [f"Generated by `python -m eval.run_eval` on {r['generated_at'][:10]} · {r['diagnosis']['n']} diagnosis cases.", "",
             "| Diagnosis | Top-1 | Top-3 | Avg. time | Failed calls |", "|---|---|---|---|---|"]
    for k, m in r["diagnosis"]["modes"].items():
        name = "Muse Spark + repair sources (HOLOFIX)" if k == "grounded" else "Muse Spark alone"
        lines.append(f"| {name} | {pct(m['top1'])} | {pct(m['top3'])} | {m['avg_seconds']} s | {m['errors']} |")
    s = r["safety"]
    lines += ["", f"**Safety:** {s['caught']}/{s['n']} dangerous cases stopped with no repair steps; "
              f"{s['false_stops']} false alarms on the {r['diagnosis']['n'] - s['n']} ordinary cases.", ""]
    if r["extraction"]:
        lines += ["| Parts extraction | Reference parts found (recall) | Parts extracted |", "|---|---|---|"]
        for e in r["extraction"]:
            lines.append(f"| {e['device']} | {pct(e['recall'])} ({e['matched']}/{e['expected']}) | {e['extracted']} |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=4)
    args = ap.parse_args()

    cases = json.loads((EVAL / "cases.json").read_text())["cases"]
    paths = featured_paths()
    graphs, skipped = {}, []
    for c in cases:
        f = paths.get(c["device"])
        if c["device"].startswith("MacBook Air M1") and (not f or not f.exists()):
            f = config.DATA_DIR / "samples" / "macbook_air_m1_2020.json"
        if f and f.exists():
            graphs[c["device"]] = PartsGraph.model_validate_json(f.read_text())
        else:
            skipped.append(c["device"])
    runnable = [c for c in cases if c["device"] in graphs]
    print(f"{len(runnable)} cases on {len(graphs)} devices"
          + (f" (skipped, not prebuilt: {sorted(set(skipped))})" if skipped else ""))

    # Answers are cached on disk, so a re-run returns them instantly. Keep the time measured on the
    # run that actually called the API (from the previous cases.csv), so "Avg. time" stays real.
    measured = {}
    if OUT_CSV.exists():
        with OUT_CSV.open() as fh:
            for row in csv.DictReader(fh):
                if not row["error"]:
                    measured[(row["symptom"], row["mode"])] = float(row["seconds"])

    results = {"alone": [None] * len(runnable), "grounded": [None] * len(runnable)}
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        futures = {pool.submit(run_case, c, graphs[c["device"]], mode == "grounded"): (mode, i)
                   for mode in results for i, c in enumerate(runnable)}
        done = 0
        for f, (mode, i) in futures.items():
            r = results[mode][i] = f.result()
            done += 1
            if not r["error"] and r["seconds"] < 2 and (runnable[i]["symptom"], mode) in measured:
                r["seconds"] = measured[(runnable[i]["symptom"], mode)]
            mark = "ok " if r["top3"] else "-- "
            print(f"  [{done:>2}/{len(futures)}] {mode:<8} {mark} {runnable[i]['symptom'][:60]:<60} -> {', '.join(r['suspects'][:2]) or r['error']}")

    modes = {}
    for mode, rs in results.items():
        n = len(rs)
        modes[mode] = {"top1": round(sum(r["top1"] for r in rs) / n, 3), "top3": round(sum(r["top3"] for r in rs) / n, 3),
                       "avg_seconds": round(sum(r["seconds"] for r in rs) / n, 1), "errors": sum(1 for r in rs if r["error"])}
    stop_cases = [i for i, c in enumerate(runnable) if c["expect_stop"]]
    caught = sum(1 for i in stop_cases if results["grounded"][i]["stop"])
    false_stops = sum(1 for i, c in enumerate(runnable) if not c["expect_stop"] and results["grounded"][i]["stop"])

    report = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "model": config.META_MODEL,
        "diagnosis": {"n": len(runnable), "modes": modes},
        "safety": {"n": len(stop_cases), "caught": caught, "false_stops": false_stops},
        "extraction": extraction_scores(paths),
    }
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(report, indent=2))

    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    with OUT_CSV.open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["device", "symptom", "expected", "mode", "top1", "top3", "safety_stop", "suspects", "seconds", "error"])
        for i, c in enumerate(runnable):
            for mode in results:
                r = results[mode][i]
                w.writerow([c["device"], c["symptom"], "|".join(c["expect"]), mode, r["top1"], r["top3"], r["stop"],
                            " > ".join(r["suspects"]), r["seconds"], r["error"] or ""])

    readme = ROOT / "README.md"
    if readme.exists():
        text = readme.read_text()
        start, end = "<!-- EVAL:START -->", "<!-- EVAL:END -->"
        if start in text and end in text:
            text = text[:text.index(start) + len(start)] + "\n" + readme_table(report) + "\n" + text[text.index(end):]
            readme.write_text(text)

    print("\n" + readme_table(report))
    print(f"\nfalse safety stops on non-dangerous cases: {false_stops}")
    print(f"written: {OUT_JSON.relative_to(ROOT)}, {OUT_CSV.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
